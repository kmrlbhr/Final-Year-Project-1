"""Train the local URL-feature Random Forest and export it for the extension."""

from __future__ import annotations

import csv
import io
import json
import urllib.request
import zipfile
from pathlib import Path

from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report
from sklearn.model_selection import train_test_split


DATASET_URL = "https://archive.ics.uci.edu/static/public/327/phishing+websites.zip"
FEATURE_NAMES = [
    "having_IP_Address",
    "URL_Length",
    "Shortining_Service",
    "having_At_Symbol",
    "double_slash_redirecting",
    "Prefix_Suffix",
    "having_Sub_Domain",
]
OUTPUT_PATH = Path(__file__).with_name("random_forest_model.js")


def load_dataset() -> tuple[list[list[float]], list[int]]:
    request = urllib.request.Request(
        DATASET_URL, headers={"User-Agent": "ShieldPhish model trainer"}
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        archive_bytes = response.read()

    with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
        dataset_name = next(
            name for name in archive.namelist() if name.endswith("Training Dataset.arff")
        )
        dataset_text = archive.read(dataset_name).decode("utf-8")

    data_started = False
    features: list[list[float]] = []
    labels: list[int] = []
    for line in dataset_text.splitlines():
        line = line.strip()
        if not line or line.startswith("%"):
            continue
        if line.lower() == "@data":
            data_started = True
            continue
        if not data_started:
            continue

        values = next(csv.reader([line]))
        features.append([float(value) for value in values[: len(FEATURE_NAMES)]])
        labels.append(1 if values[-1].strip() == "-1" else 0)

    if not features:
        raise ValueError("The UCI ARFF file contained no training rows.")
    return features, labels


def export_model(model: RandomForestClassifier) -> None:
    phishing_class_index = list(model.classes_).index(1)
    trees = []

    for estimator in model.estimators_:
        tree = estimator.tree_
        nodes = []
        for node_index in range(tree.node_count):
            values = tree.value[node_index][0]
            total = float(sum(values))
            nodes.append(
                {
                    "left": int(tree.children_left[node_index]),
                    "right": int(tree.children_right[node_index]),
                    "feature": int(tree.feature[node_index]),
                    "threshold": float(tree.threshold[node_index]),
                    "phishing": float(values[phishing_class_index] / total),
                }
            )
        trees.append(nodes)

    model_data = {
        "features": FEATURE_NAMES,
        "phishingLabel": 1,
        "trees": trees,
    }
    OUTPUT_PATH.write_text(
        "// Generated by train_model.py; do not edit by hand.\n"
        "globalThis.shieldPhishRandomForest = "
        + json.dumps(model_data, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )


def main() -> None:
    features, labels = load_dataset()
    train_features, test_features, train_labels, test_labels = train_test_split(
        features,
        labels,
        test_size=0.20,
        random_state=42,
        stratify=labels,
    )
    evaluation_model = RandomForestClassifier(
        n_estimators=64,
        max_depth=8,
        min_samples_leaf=3,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1,
    )
    evaluation_model.fit(train_features, train_labels)
    predictions = evaluation_model.predict(test_features)
    print(f"Dataset rows: {len(labels)}")
    print(f"Holdout accuracy: {accuracy_score(test_labels, predictions):.3f}")
    print(classification_report(test_labels, predictions, target_names=["legitimate", "phishing"]))

    deployment_model = RandomForestClassifier(
        n_estimators=64,
        max_depth=8,
        min_samples_leaf=3,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1,
    )
    deployment_model.fit(features, labels)
    export_model(deployment_model)
    print(f"Exported model: {OUTPUT_PATH} ({OUTPUT_PATH.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()